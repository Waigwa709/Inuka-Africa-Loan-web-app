// Helper to compute loans with derived statuses and balances
export function getInitialLoans(): Loan[] {
  return INITIAL_LOANS_DATA.map((item) => {
    const outstanding = Math.max(0, item.totalAmountDue - item.totalRepaid);
    const status = deriveLoanStatus(item.totalAmountDue, item.totalRepaid);
    return {
      ...item,
      outstandingBalance: outstanding,
      status,
    };
  });
}
